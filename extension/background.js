// Foldreel browser extension - background service worker.
//
// Talks straight to the loopback backend that a running copy of Foldreel opens
// on this same machine (http://127.0.0.1:8767) - nothing here ever leaves
// localhost. Pairing works by asking Foldreel's own Settings page to mint a
// persistent secret (separate from the per-run token the Electron app uses
// internally, since this extension has no way to receive that one) and
// pasting it into options.html once; see options.js for that flow.

const API_HOST = 'http://127.0.0.1:8767';

async function getSecret() {
  const { secret } = await chrome.storage.local.get('secret');
  return secret || '';
}

async function sendUrls(urls, options) {
  const secret = await getSecret();
  if (!secret) {
    chrome.runtime.openOptionsPage();
    return { ok: false, reason: 'not-paired' };
  }
  try {
    const res = await fetch(`${API_HOST}/api/extension/jobs`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'X-Foldreel-Extension-Token': secret,
      },
      body: JSON.stringify(options ? { urls, options } : { urls }),
    });
    if (res.status === 401) return { ok: false, reason: 'unauthorized' };
    if (!res.ok) return { ok: false, reason: 'error' };
    return { ok: true };
  } catch {
    // Foldreel isn't running, or nothing is listening on the port yet.
    return { ok: false, reason: 'offline' };
  }
}

// Same idea as the third-party "Get cookies.txt LOCALLY" extension Foldreel's
// own Settings page still links out to for people without this extension -
// except here it's one click with no separate export-then-upload round
// trip, since the "cookies" permission already gives direct access to the
// active tab's own cookies.
function toNetscapeCookiesTxt(cookies) {
  const lines = ['# Netscape HTTP Cookie File', '# Generated by Foldreel'];
  for (const c of cookies) {
    // chrome.cookies' own domain string already carries the leading "." for
    // a subdomain-wide cookie; hostOnly ones (no leading dot) are exact-host
    // only. The Netscape flag column just mirrors whichever this cookie is.
    const flag = c.domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const expiry = c.session ? '0' : String(Math.round(c.expirationDate || 0));
    lines.push([c.domain, flag, c.path, c.secure ? 'TRUE' : 'FALSE', expiry, c.name, c.value].join('\t'));
  }
  return lines.join('\n') + '\n';
}

async function exportCookies(url) {
  const secret = await getSecret();
  if (!secret) {
    chrome.runtime.openOptionsPage();
    return { ok: false, reason: 'not-paired' };
  }
  let host;
  try { host = new URL(url).hostname; } catch { return { ok: false, reason: 'error' }; }
  let cookies;
  try { cookies = await chrome.cookies.getAll({ url }); } catch { return { ok: false, reason: 'error' }; }
  if (!cookies.length) return { ok: false, reason: 'no-cookies' };
  try {
    const res = await fetch(`${API_HOST}/api/extension/cookies`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'X-Foldreel-Extension-Token': secret },
      body: JSON.stringify({ domain: host, text: toNetscapeCookiesTxt(cookies) }),
    });
    if (res.status === 401) return { ok: false, reason: 'unauthorized' };
    if (!res.ok) return { ok: false, reason: 'error' };
    const data = await res.json();
    return { ok: true, domains: data.domains || [], count: data.cookies || 0, replaced: !!data.replaced };
  } catch {
    return { ok: false, reason: 'offline' };
  }
}

// Whether Foldreel already holds cookies for this site, so the popup can say
// "Replace" instead of "Add" and show how old the saved copy is.
async function cookieStatus(url) {
  const secret = await getSecret();
  if (!secret) return { ok: false, reason: 'not-paired' };
  let host;
  try { host = new URL(url).hostname; } catch { return { ok: false, reason: 'error' }; }
  try {
    const res = await fetch(`${API_HOST}/api/extension/cookies?domain=${encodeURIComponent(host)}`, {
      headers: { 'X-Foldreel-Extension-Token': secret },
    });
    if (res.status === 401) return { ok: false, reason: 'unauthorized' };
    if (!res.ok) return { ok: false, reason: 'error' };
    return { ok: true, ...(await res.json()) };
  } catch {
    return { ok: false, reason: 'offline' };
  }
}

// Lets the popup show connection state as soon as it opens, instead of only
// finding out whether pairing works when the user hits Send. Reuses the same
// /api/extension/ping the options page already checks a pasted code with.
async function checkConnection() {
  const secret = await getSecret();
  if (!secret) return { ok: false, reason: 'not-paired' };
  try {
    const res = await fetch(`${API_HOST}/api/extension/ping`, {
      headers: { 'X-Foldreel-Extension-Token': secret },
    });
    if (res.status === 401) return { ok: false, reason: 'unauthorized' };
    if (!res.ok) return { ok: false, reason: 'error' };
    return { ok: true };
  } catch {
    return { ok: false, reason: 'offline' };
  }
}

// Some sites (usually ones gallery-dl/yt-dlp have no extractor for) point a
// plain <video src="..."> straight at a CDN URL, or stream HLS/DASH through a
// script, instead of exposing any download link - the same URL you'd
// otherwise dig out of the DevTools Network tab by hand. Chrome's webRequest
// API sees those requests the moment the page makes them. Two kinds are kept:
//   - `type: 'media'`: what a real <video>/<audio> element's own request shows
//     up as.
//   - a stream playlist (.m3u8 / .mpd) fetched by the page's own script. Only
//     the playlist is kept; every other fetch/XHR is ignored, so YouTube,
//     X/Twitter and the rest (which have proper extractors) are untouched.
// The first request per page load wins (a preroll ad firing later shouldn't
// override the video the user wants), except that a playlist replaces a plain
// media file seen earlier. The page that made the request is stored too:
// many CDNs answer a request without the right Referer with a placeholder
// clip instead of the video. Cleared the moment the tab's main page navigates
// again.
const STREAM_PLAYLIST = /\.(?:m3u8|mpd)(?:[?#]|$)/i;

chrome.webRequest.onBeforeRequest.addListener(
  (details) => {
    if (details.tabId < 0) return;
    const key = `media_${details.tabId}`;
    if (details.type === 'main_frame') {
      chrome.storage.session.remove([key, `blocked_${details.tabId}`]);
      return;
    }
    const playlist = STREAM_PLAYLIST.test(details.url);
    if (details.type !== 'media' && !playlist) return;
    const referer = details.documentUrl || (details.initiator ? `${details.initiator}/` : '');
    chrome.storage.session.get(key).then((got) => {
      const prev = got[key];
      if (prev && !(playlist && !prev.playlist)) return; // first-seen-wins for this page load
      chrome.storage.session.set({ [key]: { url: details.url, referer, playlist, ts: Date.now() } });
    });
  },
  { urls: ['<all_urls>'], types: ['media', 'main_frame', 'xmlhttprequest', 'other'] },
);

chrome.tabs.onRemoved.addListener((tabId) => {
  chrome.storage.session.remove([`media_${tabId}`, `blocked_${tabId}`]);
});

// How many pop-ups and invisible layers the blocker stopped on a tab's current page,
// for the toolbar popup. Reported by the content scripts (any frame); counts are
// added one at a time so two frames reporting together do not overwrite each other.
let blockedQueue = Promise.resolve();
function addBlocked(tabId, n) {
  const key = `blocked_${tabId}`;
  blockedQueue = blockedQueue
    .then(() => chrome.storage.session.get(key))
    .then((got) => chrome.storage.session.set({ [key]: (got[key] || 0) + n }))
    .catch(() => {});
}

async function getCapturedMedia(tabId) {
  const key = `media_${tabId}`;
  const got = await chrome.storage.session.get(key);
  return got[key] || null;
}

// The popup runs in its own context (MV3 has no shared module scope between
// it and this service worker), so it reaches sendUrls/checkConnection
// through a message instead of a direct call - this also keeps the pairing
// secret out of the popup's own code entirely.
chrome.runtime.onMessage.addListener((msg, sender, sendResponse) => {
  if (msg?.type === 'popups-blocked') {
    // Only this extension's own content scripts, and only for the tab they run in.
    const n = Math.min(Math.max(parseInt(msg.n, 10) || 0, 0), 1000);
    if (sender.id === chrome.runtime.id && sender.tab?.id != null && n) addBlocked(sender.tab.id, n);
    return false;
  }
  if (msg?.type === 'popups-count') {
    blockedQueue.then(() => chrome.storage.session.get(`blocked_${msg.tabId}`))
      .then((got) => sendResponse({ count: got[`blocked_${msg.tabId}`] || 0 }))
      .catch(() => sendResponse({ count: 0 }));
    return true;
  }
  if (msg?.type === 'send') {
    sendUrls(msg.urls, msg.options).then(sendResponse);
    return true; // keep the message channel open for the async sendResponse
  }
  if (msg?.type === 'status') {
    checkConnection().then(sendResponse);
    return true;
  }
  if (msg?.type === 'captured-media') {
    getCapturedMedia(msg.tabId).then(sendResponse);
    return true;
  }
  if (msg?.type === 'export-cookies') {
    exportCookies(msg.url).then(sendResponse);
    return true;
  }
  if (msg?.type === 'cookie-status') {
    cookieStatus(msg.url).then(sendResponse);
    return true;
  }
  return false;
});

const BADGE = {
  ok: { text: '✓', color: '#10b981' },
  offline: { text: '!', color: '#ef4444' },
  unauthorized: { text: '?', color: '#f59e0b' },
  error: { text: '!', color: '#ef4444' },
  'not-paired': { text: '?', color: '#f59e0b' },
};

async function flashBadge(result) {
  const badge = BADGE[result.ok ? 'ok' : result.reason] || BADGE.error;
  await chrome.action.setBadgeBackgroundColor({ color: badge.color });
  await chrome.action.setBadgeText({ text: badge.text });
  setTimeout(() => chrome.action.setBadgeText({ text: '' }), 2000);
}

// The toolbar button opens popup.html instead of firing this (a
// default_popup in the manifest means Chrome never dispatches onClicked at
// all); only the two context-menu entries below still go straight through
// with a badge flash, since they're already a single deliberate target.
chrome.runtime.onInstalled.addListener(() => {
  chrome.contextMenus.create({
    id: 'foldreel-send-link',
    title: 'Send link to Foldreel',
    contexts: ['link'],
  });
  chrome.contextMenus.create({
    id: 'foldreel-send-page',
    title: 'Send this page to Foldreel',
    contexts: ['page'],
  });
});

chrome.contextMenus.onClicked.addListener(async (info, tab) => {
  const url = info.menuItemId === 'foldreel-send-link' ? info.linkUrl : (info.pageUrl || tab?.url);
  if (!url) return;
  await flashBadge(await sendUrls([url]));
});

// Keyboard shortcut (Alt+Shift+F by default, rebindable at
// chrome://extensions/shortcuts): send the current page without opening the popup.
chrome.commands.onCommand.addListener(async (command) => {
  if (command !== 'send-page') return;
  const [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
  if (!tab?.url || !/^https?:\/\//.test(tab.url)) return;
  await flashBadge(await sendUrls([tab.url]));
});
